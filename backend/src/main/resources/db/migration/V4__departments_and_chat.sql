-- =====================================================================
-- 科室实体（V4）+ 人工坐诊会话
--
-- 为什么把科室从"写死的字符串"升级成实体：
--   ① 总后台需要能增删改科室（用户诉求）；
--   ② 医护登录时必须选择"本次坐诊科室"，不能靠前后端各自硬编码
--      （写死字符串的下场：改名要改代码，且拼错不报错，只是永远匹配不上）。
--
-- chat_sessions / chat_messages 支撑「AI 问诊 → 转人工 → 医生接诊 → 即时沟通
-- → 结束落就诊」这条链路。状态机只有三态，刻意保持简单：
--   WAITING  已转人工，等待医生接诊（在科室队列里）
--   HUMAN    医生已接诊，患者与该医生实时对话
--   CLOSED   已结束（结束时会落一条 Encounter 到业务库）
-- =====================================================================

CREATE TABLE departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64)  NOT NULL UNIQUE,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order  INT          NOT NULL DEFAULT 100,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

INSERT INTO departments (name, active, sort_order, created_at) VALUES
    ('发热门诊', TRUE, 10, CURRENT_TIMESTAMP),
    ('心内科',   TRUE, 20, CURRENT_TIMESTAMP),
    ('急诊内科', TRUE, 30, CURRENT_TIMESTAMP),
    ('骨科',     TRUE, 40, CURRENT_TIMESTAMP),
    ('感染科',   TRUE, 50, CURRENT_TIMESTAMP);

CREATE TABLE chat_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_ref     VARCHAR(128) NOT NULL,
    department      VARCHAR(64)  NOT NULL,
    status          VARCHAR(16)  NOT NULL,      -- WAITING / HUMAN / CLOSED
    chief_complaint VARCHAR(512),
    urgency         VARCHAR(32),
    assigned_staff  VARCHAR(64),
    assigned_name   VARCHAR(128),
    last_message    VARCHAR(512),
    last_message_at TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_chat_sessions_dept_status ON chat_sessions (department, status);
CREATE INDEX idx_chat_sessions_patient     ON chat_sessions (patient_ref, status);

CREATE TABLE chat_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT       NOT NULL REFERENCES chat_sessions (id),
    sender      VARCHAR(16)  NOT NULL,          -- PATIENT / DOCTOR / SYSTEM
    sender_name VARCHAR(128),
    body        VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_chat_messages_session ON chat_messages (session_id, id);
