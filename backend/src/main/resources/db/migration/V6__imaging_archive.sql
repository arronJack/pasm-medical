-- =====================================================================
-- 影像归档 + 转交（V6，2026-11-06）
--
-- ★ 边界（写进表结构，不是只写在文档里）：
--   本表**只存「原始字节的引用 + 检查元数据 + 谁转交给谁」**，
--   刻意**没有任何** impression / findings / conclusion / ai_result /
--   report_text 之类的结论字段 —— 影像自动分析属高风险诊断行为，
--   无三类医疗器械注册证不做（见 docs/COMPLIANCE-GATE.md §3）。
--   没有字段，就不存在「某天顺手把模型结论写进来」的旁路。
--
-- ★ 原始字节落本地目录（medical.imaging.dir，默认 .demo/imaging），
--   库里只存相对 storage_key + sha256（完整性校验）+ 声明的 content_type。
--   服务端**从不解析像素 / DICOM 标签**，只做字节搬运与哈希。
--   生产应把这一层换成 PACS / MinIO 适配器 + 加密与留存策略（见 GUIDE）。
--
-- ⚠ dev(H2) 与生产(PG) 共用同一份迁移；已应用的版本永不修改。
-- =====================================================================

CREATE TABLE imaging_studies (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_ref         VARCHAR(128) NOT NULL,
    modality            VARCHAR(32)  NOT NULL,       -- CT / MR / XRAY / US / 其他（原样登记，不做编码映射）
    body_part           VARCHAR(128) NOT NULL,
    study_date          VARCHAR(32),                 -- 检查日期原样字符串，不解析
    accession_no        VARCHAR(128),                -- 院内检查号 / DICOM StudyInstanceUID 引用
    department          VARCHAR(64)  NOT NULL DEFAULT '',  -- 患者指定的接收科室；空 = 未指定
    file_name           VARCHAR(256) NOT NULL,
    content_type        VARCHAR(128) NOT NULL,
    byte_size           BIGINT       NOT NULL,
    sha256              VARCHAR(64)  NOT NULL,
    storage_key         VARCHAR(256) NOT NULL,       -- 相对路径，服务端生成（UUID），绝不使用用户文件名
    status              VARCHAR(24)  NOT NULL,       -- ARCHIVED / HANDED_OFF
    handoff_department  VARCHAR(64),
    handoff_note        VARCHAR(1024),
    handoff_by          VARCHAR(64),
    handoff_at          TIMESTAMP WITH TIME ZONE,
    uploaded_by         VARCHAR(64)  NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_imaging_patient   ON imaging_studies (patient_ref, created_at);
CREATE INDEX idx_imaging_status    ON imaging_studies (status, department);
CREATE INDEX idx_imaging_handoff   ON imaging_studies (handoff_department, status);
