-- =====================================================================
-- 自学习候选知识池（V3）
--
-- 每日批处理从近期就诊抽取「可沉淀为资料的经验候选」，先进入候选池，
-- 不直接生效（human-in-the-loop）。审核台审核通过后，才 upsert 进
-- knowledge_docs 并 bump 知识池版本（可回滚）。这是 PLAN §8 自学习闭环的
-- 「候选池 + 审核台 + 版本回滚」三件套，对应四条铁律：
--   ① 学习只进候选池，生效必须过审；
--   ② 可回滚（知识池版本化）；
--   ③ 影子评测（本版未做，留待 P3 深化）；
--   ④ 禁止在线改权重（第一版只动资料库，不碰模型）。
--
-- status:
--   PENDING  待审
--   APPROVED 已采纳入库（已 upsert 进 knowledge_docs）
--   REJECTED 已驳回（不入库）
--   CONFLICT 与现库资料冲突（同标题、结论相反），挂起待人工裁定
--
-- 知识池版本号不单独建表，复用 system_config 键值表（config_key = 'kb_pool_version'），
-- 与机构对接设置同库同源、便于审计。
-- =====================================================================

CREATE TABLE kb_candidates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    doc_key         VARCHAR(64),      -- 目标资料键：非空 = 更新既有资料；空 = 新增
    title           VARCHAR(200)   NOT NULL,
    content         VARCHAR(8000),
    tags            VARCHAR(400),
    department      VARCHAR(64),      -- 建议归属科室（空 = 全院通用）；审核时作为授权范围
    source          VARCHAR(32)    NOT NULL DEFAULT 'daily-batch',
    status          VARCHAR(16)    NOT NULL DEFAULT 'PENDING',
    confidence      DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    conflict_with   VARCHAR(64),      -- 冲突时指向现库资料键
    evidence        VARCHAR(2000),    -- 生成依据（来源就诊 ref / 命中规则）
    fingerprint     VARCHAR(64),      -- 内容指纹（去重：同一经验不重复入池）
    pool_version    VARCHAR(32),      -- 审核通过后写入的「知识池版本」
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at     TIMESTAMP WITH TIME ZONE,
    reviewed_by     VARCHAR(64),
    CONSTRAINT pk_kb_candidates PRIMARY KEY (id)
);

COMMENT ON TABLE kb_candidates IS '自学习候选知识池：仅过审后才进 knowledge_docs，生效必须 human-in-the-loop';
COMMENT ON COLUMN kb_candidates.status IS 'PENDING / APPROVED / REJECTED / CONFLICT';
COMMENT ON COLUMN kb_candidates.fingerprint IS '归一化(title+content) 的 SHA-256，去重用';
COMMENT ON COLUMN kb_candidates.pool_version IS '审核通过时打上的知识池版本号，回滚据此定位';
COMMENT ON COLUMN kb_candidates.confidence IS '抽取完整度启发式评分(0~1)，非临床确定性，仅辅助排序';

-- 查询路径：按状态拉待审 / 按指纹去重 / 按时间倒序 / 按科室范围。
CREATE INDEX idx_kb_candidates_status      ON kb_candidates (status);
CREATE INDEX idx_kb_candidates_fingerprint ON kb_candidates (fingerprint);
CREATE INDEX idx_kb_candidates_created     ON kb_candidates (created_at DESC);
CREATE INDEX idx_kb_candidates_department  ON kb_candidates (department);
