-- =====================================================================
-- pasm-medical 初始表结构（V1）
--
-- 为什么用迁移脚本而不是 Hibernate 自动建表：
--   医疗系统的表结构变更要走**评审与变更单**。ddl-auto=update/validate 只能
--   让 ORM "猜"结构，改了什么、谁改的、能不能回滚，都留不下可评审的产物。
--   迁移脚本是版本化、可 diff、可回放的那份真相。
--
-- 命名：与 JPA 实体一一对应（Spring Boot 默认 CamelCase → snake_case）。
-- 时间：统一 TIMESTAMP WITH TIME ZONE（Java 侧是 Instant，必须带时区语义）。
-- =====================================================================

-- ---------------------------------------------------------------- 患者
CREATE TABLE patients (
    ref         VARCHAR(64)  NOT NULL,
    name        VARCHAR(64),
    sex         VARCHAR(8),
    age         INTEGER,
    allergy     VARCHAR(200),
    chronic     VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_patients PRIMARY KEY (ref)
);

COMMENT ON TABLE patients IS '患者主档（去标识化后）；ref 是业务主键，也是认知层 agent_id 的输入';

-- ---------------------------------------------------------------- 就诊
CREATE TABLE encounters (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    patient_ref      VARCHAR(64) NOT NULL,
    occurred_at      TIMESTAMP WITH TIME ZONE,
    department       VARCHAR(64),
    chief_complaint  VARCHAR(200),
    assessment       VARCHAR(400),
    plan             VARCHAR(400),
    triage_urgency   VARCHAR(16),
    summary_text     VARCHAR(4000),
    CONSTRAINT pk_encounters PRIMARY KEY (id)
);

COMMENT ON TABLE encounters IS '一次就诊/一次预问诊（FHIR Encounter 的最小投影）；不含原始对话，只存去标识化摘要';

-- ---------------------------------------------------------------- 审计
CREATE TABLE ai_audit (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    patient_ref     VARCHAR(64),
    actor           VARCHAR(64),
    action          VARCHAR(32) NOT NULL,
    evidence_count  INTEGER,
    model_version   VARCHAR(64),
    input_snapshot  VARCHAR(4000),
    refused         BOOLEAN,
    CONSTRAINT pk_ai_audit PRIMARY KEY (id)
);

COMMENT ON TABLE ai_audit IS 'AI 审计（只增不改）；生产应独立库 + 只授 INSERT';

-- ---------------------------------------------------------------- 资料库
CREATE TABLE knowledge_docs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    doc_key     VARCHAR(64)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    content     VARCHAR(8000),
    tags        VARCHAR(400),
    department  VARCHAR(64),
    status      VARCHAR(16)  NOT NULL DEFAULT 'active',
    version     VARCHAR(32),
    reviewer    VARCHAR(64),
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by  VARCHAR(64),
    CONSTRAINT pk_knowledge_docs PRIMARY KEY (id),
    CONSTRAINT uk_knowledge_docs_doc_key UNIQUE (doc_key)
);

COMMENT ON TABLE knowledge_docs IS '机构资料库（业务库是权威；认知侧只放"当前生效"检索副本）';
COMMENT ON COLUMN knowledge_docs.department IS '归属科室；空表示全院通用（只有超管可管理）';

-- ---------------------------------------------------------------- 系统配置
CREATE TABLE system_config (
    config_key    VARCHAR(64) NOT NULL,
    config_value  VARCHAR(500),
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by    VARCHAR(64),
    CONSTRAINT pk_system_config PRIMARY KEY (config_key)
);

COMMENT ON TABLE system_config IS '对接设置（期望值）；与认知服务实际值对账见 /api/admin/config 的 drift';

-- =====================================================================
-- 索引：按**真实查询路径**建，不做"看起来齐全"的装饰性索引。
--   · 审计面板：occurred_at 倒序分页
--   · 统计：action（+时间窗）、refused
--   · 科室范围：patient_ref（+时间）
--   · 时间轴：patient_ref + occurred_at
--   · 科室患者列表：department + patient_ref
--   · 资料库：department + status
-- =====================================================================
CREATE INDEX idx_audit_occurred_at      ON ai_audit (occurred_at DESC);
CREATE INDEX idx_audit_action_time      ON ai_audit (action, occurred_at);
CREATE INDEX idx_audit_patient_time     ON ai_audit (patient_ref, occurred_at);
CREATE INDEX idx_audit_action_refused   ON ai_audit (action, refused);

CREATE INDEX idx_encounters_patient_time ON encounters (patient_ref, occurred_at);
CREATE INDEX idx_encounters_department   ON encounters (department, patient_ref);

CREATE INDEX idx_kb_department_status    ON knowledge_docs (department, status);
