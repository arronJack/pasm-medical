-- =====================================================================
-- LIS 对接：检验结果落库（V2）
--
-- 为什么单独建表而不是塞进 encounters：
--   一次就诊可以有 N 张检验单、每张单 M 个检验项；塞进就诊摘要会丢掉
--   项目级数值/单位/参考区间/异常标记，而这些正是"趋势判断"和"危急值"
--   所依赖的最小粒度。FHIR 里对应的就是 Observation。
--
-- 幂等：LIS 重发很常见（网络抖动、仪器重传）。用
--   (message_control_id, observation_seq) 唯一约束保证同一消息重复投递
--   不会变成重复结果 —— 医疗数据里"多一条"比"少一条"更危险。
-- =====================================================================

CREATE TABLE lab_results (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    patient_ref           VARCHAR(64)   NOT NULL,
    message_control_id    VARCHAR(64)   NOT NULL,
    observation_seq       INTEGER       NOT NULL,
    panel_code            VARCHAR(64),
    panel_name            VARCHAR(128),
    analyte_code          VARCHAR(64)   NOT NULL,
    analyte_name          VARCHAR(128),
    value_text            VARCHAR(128),
    value_num             NUMERIC(18, 6),
    unit                  VARCHAR(32),
    ref_low               NUMERIC(18, 6),
    ref_high              NUMERIC(18, 6),
    ref_range_text        VARCHAR(64),
    abnormal_flag         VARCHAR(16),
    abnormal_flag_raw     VARCHAR(8),
    result_status         VARCHAR(8),
    observed_at           TIMESTAMP WITH TIME ZONE,
    source                VARCHAR(16)   NOT NULL DEFAULT 'hl7',
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_lab_results PRIMARY KEY (id),
    CONSTRAINT uk_lab_results_msg_seq UNIQUE (message_control_id, observation_seq)
);

COMMENT ON TABLE lab_results IS 'LIS 检验结果（项目级）；只落结构化结果，不写入认知记忆';
COMMENT ON COLUMN lab_results.abnormal_flag IS '归一化异常标记：high/low/normal/abnormal/unknown';
COMMENT ON COLUMN lab_results.abnormal_flag_raw IS 'LIS 原始异常标记（H/L/HH/LL/N/A），用于对账，不参与判读';
COMMENT ON COLUMN lab_results.result_status IS 'OBX-11 结果状态：F 最终 / P 初步 / C 更正';
COMMENT ON COLUMN lab_results.source IS '来源通道：hl7 / fhir';

-- 查询路径：患者时间轴（按时间倒序取最近结果）、按检验单回看。
CREATE INDEX idx_lab_results_patient_time ON lab_results (patient_ref, observed_at DESC);
CREATE INDEX idx_lab_results_panel        ON lab_results (patient_ref, panel_code);
CREATE INDEX idx_lab_results_abnormal     ON lab_results (patient_ref, abnormal_flag);
