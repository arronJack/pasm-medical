"""``pasm_medical`` —— 医院智能诊疗辅助系统的**认知服务侧**。

定位
----
本项目是 **PASM 生态里的一个应用**（不是引擎的一部分），独立仓、独立包、独立发版。
它把 PASM 的「记忆 / 情绪 / 成长」落到医疗语义上，并通过 HTTP 暴露给
Spring Boot 业务层（见 ``docs/PLAN.md`` 的分层设计）。

为什么医疗侧要单独一层而不是直接调 PASM
----------------------------------------
医疗场景比通用问答多了三层强约束，这三层必须**在业务侧显式表达**，不能指望模型自觉：

1. **合规红线**（:mod:`.safety`）—— 不得自动生成处方 / 医嘱；每条输出必须可追溯到
   依据；不确定必须说不知道。这些是**代码级**约束，不是提示词。
2. **患者隔离**（:mod:`.domain`）—— 认知实例按「患者」分片。PASM 的知识库默认落点
   是全机共享的，不显式分片会跨患者串库 —— 这在医疗场景是数据泄露。
3. **确定性计算**（:mod:`.domain`）—— 评分表、剂量、配伍禁忌必须是**规则代码**，
   绝不交给 LLM。LLM 只做语言理解与解释。

模块
----
- :mod:`.domain`   患者 / 就诊 / 病历的领域模型 + 患者级 agent_id 约定
- :mod:`.safety`   医疗安全护栏（拒绝自动处方、必带依据、拒答能力）
- :mod:`.service`  装配 PASM 应用并通过 HTTP 暴露（认知 API + 医疗 API）
"""

